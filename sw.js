self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

function limpiar() {
  return caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('doble-vida-') && k !== CACHE).map((k) => caches.delete(k))));
}

/**
 * Una petición que el worker viejo tuviera en marcha puede resucitar su caché: se barre al navegar.
 * Solo el worker vigente y sin otro instalándose: si no, borraría la caché nueva a medio llenar.
 */
function barrer() {
  const r = self.registration;
  if (r.installing || r.waiting || (self.serviceWorker && r.active !== self.serviceWorker)) return Promise.resolve();
  return limpiar();
}

self.addEventListener('activate', (e) => {
  e.waitUntil(limpiar().then(() => self.clients.claim()));
});

async function desdeCache(pet) {
  const c = await caches.open(CACHE);
  const r = await c.match(pet, { ignoreSearch: true });
  if (r) return r;
  if (pet.mode === 'navigate') return c.match('index.html');
  return Response.error();
}

async function primeroRed(pet) {
  const c = await caches.open(CACHE);
  const corte = new AbortController();
  const reloj = setTimeout(() => corte.abort(), ESPERA_RED);
  try {
    const r = await fetch(pet, { signal: corte.signal });
    if (r.ok && r.type === 'basic') await c.put(pet, r.clone());
    return r;
  } catch {
    return desdeCache(pet);
  } finally {
    clearTimeout(reloj);
  }
}

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || !e.request.url.startsWith(self.location.origin)) return;
  if (e.request.mode === 'navigate') e.waitUntil(barrer());
  e.respondWith(primeroRed(e.request));
});
